using System.Security.Cryptography;
using LanguageLearning.Core.Accounts;
using LanguageLearning.Core.Administration;
using LanguageLearning.Core.Classrooms;
using LanguageLearning.Infrastructure.Data;
using LanguageLearning.Infrastructure.Identity;
using Microsoft.AspNetCore.Identity;
using Microsoft.EntityFrameworkCore;

namespace LanguageLearning.Infrastructure.Accounts;

// Explicit operator command only. No HTTP route, fixed password or public role selector.
public sealed partial class PresentationAccountProvisioner(LexiGoDbContext database, UserManager<ApplicationUser> users, TimeProvider clock, TeacherAccessHasher teacherCodes)
{
    public const string Domain = "@presentation.lexigo.invalid";

    public async Task<PresentationAccountEnvelope> CreateAsync(string publicKeyPem, CancellationToken token)
    {
        // Validate the public encryption key before creating anything.
        using (var rsa = RSA.Create())
        {
            rsa.ImportFromPem(publicKeyPem);
            if (rsa.KeySize < 3072) throw new InvalidOperationException("Use a 3072-bit public key.");
        }
        await using var transaction = await database.Database.BeginTransactionAsync(token);
        await database.Database.ExecuteSqlRawAsync("SELECT pg_advisory_xact_lock(730027001)", token);
        if (await database.Users.AnyAsync(user => user.Email != null && user.Email.EndsWith(Domain), token))
            throw new InvalidOperationException("Presentation accounts already exist. Use the saved encrypted credentials; existing accounts will not be promoted or reset.");

        var definitions = new[]
        {
            new AccountDefinition("tutor-es", "Presentation tutor · Spanish", [RoleNames.Teacher], 2),
            new AccountDefinition("tutor-it", "Presentation tutor · Italian", [RoleNames.Teacher], 3),
            new AccountDefinition("tutor-de", "Presentation tutor · German", [RoleNames.Teacher], 4),
            new AccountDefinition("tutor-ru", "Presentation tutor · Russian", [RoleNames.Teacher], 5),
            new AccountDefinition("author", "Presentation content author", [RoleNames.ContentAuthor], null),
            new AccountDefinition("reviewer", "Presentation language reviewer", [RoleNames.Reviewer], null),
            // Administrator access still requires the existing password + fresh MFA bootstrap command.
            new AccountDefinition("operator", "Presentation operator", [], null)
        };
        var credentials = new List<PresentationCredential>();
        foreach (var definition in definitions)
        {
            string email = definition.Name + Domain;
            string password = "Lg!9" + RandomNumberGenerator.GetHexString(40);
            var user = new ApplicationUser
            {
                Id = Guid.NewGuid(),
                UserName = email,
                Email = email,
                DisplayName = definition.DisplayName,
                EmailConfirmed = true,
                CreatedAt = clock.GetUtcNow()
            };
            Ensure(await users.CreateAsync(user, password));
            Ensure(await users.AddToRoleAsync(user, RoleNames.Learner));
            foreach (var role in definition.Roles) Ensure(await users.AddToRoleAsync(user, role));
            Ensure(await users.ResetAuthenticatorKeyAsync(user));
            string key = (await users.GetAuthenticatorKeyAsync(user))!;
            Ensure(await users.SetTwoFactorEnabledAsync(user, true));
            string[] recoveryCodes = (await users.GenerateNewTwoFactorRecoveryCodesAsync(user, 10))!.ToArray();
            database.UserPreferences.Add(new UserPreference { UserId = user.Id, TimeZone = "Asia/Tbilisi" });
            int[] scopes = definition.LanguageId is { } language ? [language] : [2, 3, 4, 5];
            foreach (int scope in scopes) database.UserLanguageScopes.Add(new UserLanguageScope { UserId = user.Id, LanguageId = scope });
            if (definition.LanguageId is { } target)
            {
                var course = await database.Courses.SingleAsync(item => item.SourceLanguageId == 1 && item.TargetLanguageId == target, token);
                database.ExtraStudyOffers.Add(new ExtraStudyOffer { TeacherId = user.Id, CourseId = course.Id, Enabled = true });
                database.Classrooms.Add(new Classroom
                {
                    TeacherId = user.Id,
                    CourseId = course.Id,
                    Name = definition.DisplayName + " · practice class",
                    Description = "Presentation classroom. Invitations are generated by its teacher."
                });
            }
            database.AuditLogs.Add(new AuditLog
            {
                ActorId = null,
                Action = "PresentationAccountProvisioned",
                EntityType = "User",
                EntityId = user.Id.ToString(),
                Reason = "Explicit operator-created fictional presentation account with generated credentials and mandatory MFA.",
                TraceId = Guid.NewGuid().ToString("N"),
                OccurredAt = clock.GetUtcNow()
            });
            credentials.Add(new(email, definition.DisplayName, password, key, recoveryCodes, definition.Name == "operator"));
        }
        await database.SaveChangesAsync(token);
        var envelope = PresentationAccountEncryption.Encrypt(credentials, publicKeyPem);
        await transaction.CommitAsync(token);
        return envelope;
    }

    private static void Ensure(IdentityResult result)
    {
        if (!result.Succeeded) throw new InvalidOperationException("Presentation account setup failed. No credentials were logged.");
    }

    private sealed record AccountDefinition(string Name, string DisplayName, string[] Roles, int? LanguageId);
    private sealed record PresentationCredential(string Email, string DisplayName, string Password,
        string AuthenticatorKey, string[] RecoveryCodes, bool BootstrapCandidate);
}
