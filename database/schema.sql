            SELECT 1 FROM "HeartRefillPurchases" p WHERE p."Id" = purchase_id AND (
                (p."Status" = 'Succeeded' AND NOT EXISTS (
                    SELECT 1 FROM "CardTransactions" t JOIN "TestCards" c ON c."Id" = t."TestCardId"
